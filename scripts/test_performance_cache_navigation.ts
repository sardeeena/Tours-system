import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const read = (path: string) => readFileSync(new URL(path, import.meta.url), 'utf8');
const cache = read('../src/services/publicDataCache.ts');
const tours = read('../src/services/tourService.ts');
const availability = read('../src/services/availabilityService.ts');
const searchModule = read('../src/components/home/SearchModule.tsx');
const settings = read('../src/services/siteSettingsService.ts');
const seo = read('../src/services/seoService.ts');
const blog = read('../src/services/blogService.ts');
const exclusive = read('../src/services/exclusiveTripService.ts');
const worker = read('../public/sw.js');
const app = read('../src/App.tsx');
const header = read('../src/components/common/Header.tsx');
const server = read('../server.ts');

assert.match(cache, /localStorage\.getItem/, 'public catalogue cache persists across page reloads');
assert.match(cache, /localStorage\.setItem/, 'public catalogue cache stores successful reads');
assert.match(cache, /PUBLIC_DATA_CACHE_TTL_MS = 15 \* 60 \* 1000/, 'public editorial content has a bounded cache lifetime');
assert.match(cache, /PUBLIC_CATALOGUE_CACHE_TTL_MS = 5 \* 60 \* 1000/, 'public prices and tour catalogue use a shorter freshness window');
assert.match(tours, /catalogue:tours/, 'published tour list is cached across reloads');
assert.match(tours, /catalogue:destinations/, 'published destinations are cached across reloads');
assert.match(tours, /catalogue:categories/, 'published categories are cached across reloads');
assert.match(tours, /catalogue:tour:/, 'public tour detail content is cached across reloads');
assert.match(tours, /writePublicDataCache\('catalogue:tours'/, 'successful public catalogue reads refresh the persistent cache');
assert.match(tours, /eq\('is_exclusive', false\)/, 'public destination counts exclude Exclusive trips');
assert.match(tours, /eq\('tours\.is_exclusive', false\)/, 'public category counts exclude Exclusive trips');
assert.match(settings, /site:static-pages/, 'public CMS pages are cached across reloads');
assert.match(seo, /seo:\$\{entityType\}/, 'public SEO overrides use a persistent cache key');
assert.match(blog, /blog:list:/, 'published blog lists are cached');
assert.match(blog, /blog:post:/, 'published blog articles are cached');
assert.match(exclusive, /catalogue:exclusive-trips/, 'published Exclusive product listings are cached');
assert.doesNotMatch(availability, /readPublicDataCache|writePublicDataCache/, 'departure availability is never served from a stale public cache');
assert.match(worker, /STATIC_CACHE = 'aat-static-v2'/, 'service worker uses a versioned static asset cache');
assert.match(worker, /PRIVATE_PATH/, 'service worker excludes API and private routes');
assert.match(worker, /request\.destination === 'document'/, 'service worker never caches navigation HTML');
assert.match(worker, /request\.headers\.has\('authorization'\)/, 'service worker refuses authenticated requests');
assert.match(worker, /event\.waitUntil\(updatePromise/, 'cached assets refresh in the background');
assert.match(app, /const DeferredHomeSection/, 'homepage supports viewport-based section loading');
assert.match(app, /const needsTours = isHome \|\| path === '\/excursions'/, 'non-catalogue routes avoid loading the full tour list');
assert.match(app, /const needsDestinations = isDestinationRoute \|\| \(isHome && refreshAll\)/, 'destination data is loaded on destination routes or explicit homepage refreshes');
assert.match(app, /const needsCategories = path === '\/experiences' \|\| \(isHome && refreshAll\)/, 'category data is loaded on experience routes or explicit homepage refreshes');
assert.match(app, /onEnter=\{refreshPublishedDestinations\}/, 'homepage destination data is loaded as its section approaches');
assert.match(app, /onEnter=\{refreshPublishedCategories\}/, 'homepage category data is loaded as its section approaches');
assert.match(app, /rootMargin: '700px 0px'/, 'below-the-fold sections load shortly before entering view');
assert.match(app, /const PopularTours = lazy\(/, 'tour-card code is split from the initial homepage bundle');
assert.match(app, /const ReviewsSection = lazy\(/, 'review content is split from the initial homepage bundle');
assert.match(header, /mobile-navigation-menu/, 'mobile menu has a distinct accessible panel');
assert.match(header, /w-\[min\(25rem,calc\(100vw-1\.5rem\)\)\]/, 'mobile menu is width-constrained instead of spanning the page');
assert.match(header, /max-h-\[min\(72dvh,calc\(100dvh-5rem-env\(safe-area-inset-bottom\)\)\)\]/, 'mobile menu scrolls within the viewport on small devices');
assert.match(header, /event\.key === 'Escape'/, 'mobile menu closes with Escape');
assert.match(header, /aria-controls="mobile-navigation-menu"/, 'menu toggle identifies its controlled panel');
assert.match(seo, /logo\.png/, 'client SEO uses the canonical brand logo');
assert.match(server, /logo\.png/, 'server-rendered metadata uses the canonical brand logo');
assert.doesNotMatch(server + seo, /logo\.webp|logo\.jpg/, 'legacy logo variants are not referenced by public metadata');

console.log('Public caching boundaries, deferred loading, mobile navigation and canonical logo checks passed.');
